/**
 * 取标题里的「届别 / 年份」：
 *   - 「2027届」优先取 2027
 *   - 「2027年秋季校园招聘」「2027校园宣讲会」「2027年暑期实习」取 2027
 * 注意：实习标题里的年份是「实习年份」，不是毕业届别，页面上统一叫「年份」。
 */
export function inferCohort(...fields) {
  const text = fields.filter(Boolean).join(' ');
  const explicit = text.match(/(20[2-9]\d)\s*届/);
  if (explicit) return Number(explicit[1]);
  // 「27届」「28届」这类两位写法（前面不能紧跟数字，避免把 2027届 截成 27届）
  const short = text.match(/(?<!\d)(2[5-9])\s*届/);
  if (short) return 2000 + Number(short[1]);
  const anyYear = text.match(/(202[5-9])/);
  return anyYear ? Number(anyYear[1]) : null;
}


export function inferTags(...fields) {
  const text = fields.filter(Boolean).join(' ');
  if (!text) return [];
  const hits = [];
  for (const rule of RULES) {
    if (rule.keywords.some((kw) => text.includes(kw))) hits.push(rule.tag);
    if (hits.length >= 3) break;
  }
  return hits;
}


/** 公司名优先，其次地点、标题；避免标题里「北京/上海/深圳」多城市串误判 */
export function inferCity(...fields) {
  for (const field of fields) {
    const text = String(field || '');
    if (!text) continue;
    const hit = CITY_NAMES.find((c) => text.includes(c));
    if (hit) return hit;
  }
  return '';
}
